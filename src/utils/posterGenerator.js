/**
 * Poster Generator Utility
 * Renders the photo, caption, hashtags, and color palette into a high-resolution exportable graphics card on Canvas.
 */

export async function generateCaptionPosterCard({ photoUrl, caption, hashtags = [], palette = [], author = 'SnapCaption AI' }) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';

    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');

        // Card dimensions (standard HD square card 1200x1400)
        const canvasWidth = 1200;
        const canvasHeight = 1450;

        canvas.width = canvasWidth;
        canvas.height = canvasHeight;

        // Background dark gradient
        const bgGrad = ctx.createLinearGradient(0, 0, 0, canvasHeight);
        bgGrad.addColorStop(0, '#0b0f19');
        bgGrad.addColorStop(0.5, '#111827');
        bgGrad.addColorStop(1, '#0b0f19');
        ctx.fillStyle = bgGrad;
        ctx.fillRect(0, 0, canvasWidth, canvasHeight);

        // Draw card border glow effect
        ctx.strokeStyle = 'rgba(79, 172, 254, 0.3)';
        ctx.lineWidth = 4;
        ctx.strokeRect(30, 30, canvasWidth - 60, canvasHeight - 60);

        // Draw header badge
        ctx.fillStyle = '#4facfe';
        ctx.font = 'bold 24px sans-serif';
        ctx.fillText('✨ SNAPCAPTION AI CREATIVE CARD', 70, 90);

        // Draw image frame area (centered at top)
        const frameX = 70;
        const frameY = 120;
        const frameWidth = canvasWidth - 140;
        const frameHeight = 780;

        // Image clipping with rounded corners
        ctx.save();
        drawRoundedRect(ctx, frameX, frameY, frameWidth, frameHeight, 24);
        ctx.clip();

        // Object cover draw logic
        const imgRatio = img.naturalWidth / img.naturalHeight;
        const frameRatio = frameWidth / frameHeight;
        let drawW, drawH, drawX, drawY;

        if (imgRatio > frameRatio) {
          drawH = frameHeight;
          drawW = frameHeight * imgRatio;
          drawX = frameX - (drawW - frameWidth) / 2;
          drawY = frameY;
        } else {
          drawW = frameWidth;
          drawH = frameWidth / imgRatio;
          drawX = frameX;
          drawY = frameY - (drawH - frameHeight) / 2;
        }

        ctx.drawImage(img, drawX, drawY, drawW, drawH);
        ctx.restore();

        // Draw Palette swatches strip below image
        if (palette && palette.length > 0) {
          const swatchSize = 32;
          const swatchY = frameY + frameHeight + 35;
          ctx.font = 'bold 18px sans-serif';
          ctx.fillStyle = '#94a3b8';
          ctx.fillText('PALETTE:', 70, swatchY + 22);

          let swatchX = 170;
          palette.slice(0, 5).forEach((color) => {
            ctx.fillStyle = color;
            drawRoundedRect(ctx, swatchX, swatchY, swatchSize, swatchSize, 8);
            ctx.fill();
            ctx.strokeStyle = 'rgba(255, 255, 255, 0.2)';
            ctx.lineWidth = 1;
            ctx.stroke();
            swatchX += swatchSize + 12;
          });
        }

        // Draw Caption text box container
        const captionBoxY = frameY + frameHeight + 90;
        const captionBoxHeight = 360;
        
        ctx.fillStyle = 'rgba(255, 255, 255, 0.04)';
        drawRoundedRect(ctx, frameX, captionBoxY, frameWidth, captionBoxHeight, 20);
        ctx.fill();
        ctx.strokeStyle = 'rgba(255, 255, 255, 0.08)';
        ctx.stroke();

        // Render wrapping text for caption
        ctx.fillStyle = '#f8fafc';
        ctx.font = '32px sans-serif';
        const textMarginX = frameX + 40;
        let textY = captionBoxY + 60;

        const words = caption.split(' ');
        let currentLine = '';

        for (let i = 0; i < words.length; i++) {
          const testLine = currentLine + words[i] + ' ';
          const metrics = ctx.measureText(testLine);
          if (metrics.width > frameWidth - 80 && i > 0) {
            ctx.fillText(currentLine, textMarginX, textY);
            currentLine = words[i] + ' ';
            textY += 44;
            if (textY > captionBoxY + captionBoxHeight - 80) break;
          } else {
            currentLine = testLine;
          }
        }
        if (currentLine) {
          ctx.fillText(currentLine, textMarginX, textY);
          textY += 44;
        }

        // Draw Hashtags
        if (hashtags && hashtags.length > 0 && textY < captionBoxY + captionBoxHeight - 40) {
          ctx.fillStyle = '#38bdf8';
          ctx.font = '22px sans-serif';
          ctx.fillText(hashtags.slice(0, 5).join(' '), textMarginX, textY + 10);
        }

        // Footer brand watermark
        ctx.fillStyle = '#64748b';
        ctx.font = '20px sans-serif';
        ctx.fillText(`Generated by ${author} • ${new Date().toLocaleDateString()}`, 70, canvasHeight - 70);

        // Convert canvas to Data URL
        const dataUrl = canvas.toDataURL('image/png');
        resolve(dataUrl);
      } catch (err) {
        console.error('Poster generation failed:', err);
        reject(err);
      }
    };

    img.onerror = (err) => reject(new Error('Failed to load image for poster: ' + err.message));
    img.src = photoUrl;
  });
}

function drawRoundedRect(ctx, x, y, width, height, radius) {
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.lineTo(x + width - radius, y);
  ctx.quadraticCurveTo(x + width, y, x + width, y + radius);
  ctx.lineTo(x + width, y + height - radius);
  ctx.quadraticCurveTo(x + width, y + height, x + width - radius, y + height);
  ctx.lineTo(x + radius, y + height);
  ctx.quadraticCurveTo(x, y + height, x, y + height - radius);
  ctx.lineTo(x, y + radius);
  ctx.quadraticCurveTo(x, y, x + radius, y);
  ctx.closePath();
}
